"""Generate requirements-android.txt from the `android` extra of apps/api (uv.lock is the source of truth).

    python3 python-wheels/generate_requirements.py           # rewrite
    python3 python-wheels/generate_requirements.py --check   # exit 1 when the committed file is stale

Runs `uv export --extra android --no-dev --no-emit-project`, keeps the requirements whose markers hold on Android
(CPython 3.13, `sys_platform == "android"`), drops the markers, and applies ANDROID_OVERRIDES: packages whose
uv.lock version has no Android cp313 build, replaced by the newest build in the Chaquopy repository or PyPI.
pydantic-core, cryptg, pyaes and pillow resolve from the wheels build_all.sh puts in python-wheels/dist (`--find-links`).
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUTPUT = HERE / "requirements-android.txt"
BACKEND = HERE.parents[1] / "api"

# name -> (version, reason). Keep this list short: every entry is a deviation from the desktop lock.
ANDROID_OVERRIDES: dict[str, tuple[str, str]] = {
    "cffi": ("1.17.1", "dependency of the Chaquopy cryptography 42 build"),
    "greenlet": ("3.1.1", "newest Chaquopy-repo cp313 build"),
    "markupsafe": ("3.0.4", "first release with official android_24 wheels on PyPI"),
}
# Built locally (python-wheels/dist), noted in the output for reviewers.
LOCAL_WHEELS = {"pydantic-core", "cryptg", "pyaes", "pillow"}
# Evaluated with the target interpreter's values: CPython 3.13 on Android (arm64-v8a or x86_64).
ANDROID_ENVIRONMENTS = (
    {"sys_platform": "android", "platform_machine": "aarch64", "platform_system": "Android",
     "platform_python_implementation": "CPython", "implementation_name": "cpython", "os_name": "posix",
     "python_version": "3.13", "python_full_version": "3.13.0"},
    {"sys_platform": "android", "platform_machine": "x86_64", "platform_system": "Android",
     "platform_python_implementation": "CPython", "implementation_name": "cpython", "os_name": "posix",
     "python_version": "3.13", "python_full_version": "3.13.0"},
)
_REQUIREMENT = re.compile(r"^(?P<name>[A-Za-z0-9._-]+)==(?P<version>[^\s;]+)\s*(?:;\s*(?P<marker>.+))?$")


def export() -> str:
    return subprocess.run(
        ["uv", "export", "--quiet", "--project", str(BACKEND), "--extra", "android", "--no-dev", "--no-emit-project",
         "--no-hashes", "--no-header", "--no-annotate", "--frozen"],
        check=True, capture_output=True, text=True,
    ).stdout


def marker_holds(marker: str | None) -> bool:
    if not marker:
        return True
    from packaging.markers import Marker

    parsed = Marker(marker)
    results = {parsed.evaluate(environment) for environment in ANDROID_ENVIRONMENTS}
    if len(results) != 1:
        raise SystemExit(f"marker differs between Android ABIs: {marker}")
    return results.pop()


def render(exported: str) -> str:
    lines = [
        "# GENERATED by python-wheels/generate_requirements.py from `uv export --project apps/api --extra android`.",
        "# Do not edit: change apps/api/pyproject.toml (android extra) or ANDROID_OVERRIDES, then regenerate.",
    ]
    for raw in exported.splitlines():
        raw = raw.strip()
        if not raw or raw.startswith("#"):
            continue
        match = _REQUIREMENT.match(raw)
        if match is None:
            raise SystemExit(f"unexpected requirement line: {raw}")
        if not marker_holds(match["marker"]):
            continue
        name, version = match["name"].lower(), match["version"]
        comment = ""
        if name in ANDROID_OVERRIDES:
            override, reason = ANDROID_OVERRIDES[name]
            comment = f"  # DEVIATION (uv.lock {version}): {reason}"
            version = override
        elif name in LOCAL_WHEELS:
            comment = "  # built locally by build_all.sh (python-wheels/dist)"
        lines.append(f"{name}=={version}{comment}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when requirements-android.txt is stale")
    args = parser.parse_args()
    content = render(export())
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != content:
            print("requirements-android.txt is stale: run python-wheels/generate_requirements.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
