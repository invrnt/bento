#!/usr/bin/env node
// Converts the lucide-static SVGs listed in icons.json into Compose ImageVectors (design-system/android.md §5).
//
//   node generate_icons.mjs           write BentoIcons.kt
//   node generate_icons.mjs --check   exit 1 when the committed file differs from a fresh generation
//
// lucide-static is pinned in package.json to the lucide-react version used by apps/web.

import { readFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { writeOrCheck } from "./generate_tokens.mjs";

const here = dirname(fileURLToPath(import.meta.url));
export const iconPaths = {
  manifest: join(here, "icons.json"),
  lucideIcons: join(here, "node_modules/lucide-static/icons"),
  lucidePackage: join(here, "node_modules/lucide-static/package.json"),
  webPackage: join(here, "../../web/package.json"),
  kotlin: join(here, "../core/designsystem/src/main/kotlin/dev/bento/designsystem/generated/BentoIcons.kt"),
};

export const STROKE_DEFAULT = 2;
export const STROKE_NAV = 1.75;

const fmt = (n) => Number(Number(n).toFixed(4)).toString();

function attributes(tag) {
  const out = {};
  for (const m of tag.matchAll(/([\w-]+)="([^"]*)"/g)) out[m[1]] = m[2];
  return out;
}

function rectPath({ x = 0, y = 0, width, height, rx, ry }) {
  const w = Number(width);
  const h = Number(height);
  const x0 = Number(x);
  const y0 = Number(y);
  let rX = rx !== undefined ? Number(rx) : ry !== undefined ? Number(ry) : 0;
  let rY = ry !== undefined ? Number(ry) : rX;
  rX = Math.min(rX, w / 2);
  rY = Math.min(rY, h / 2);
  if (!rX || !rY) return `M${fmt(x0)} ${fmt(y0)}h${fmt(w)}v${fmt(h)}h${fmt(-w)}Z`;
  return [
    `M${fmt(x0 + rX)} ${fmt(y0)}`,
    `H${fmt(x0 + w - rX)}`,
    `A${fmt(rX)} ${fmt(rY)} 0 0 1 ${fmt(x0 + w)} ${fmt(y0 + rY)}`,
    `V${fmt(y0 + h - rY)}`,
    `A${fmt(rX)} ${fmt(rY)} 0 0 1 ${fmt(x0 + w - rX)} ${fmt(y0 + h)}`,
    `H${fmt(x0 + rX)}`,
    `A${fmt(rX)} ${fmt(rY)} 0 0 1 ${fmt(x0)} ${fmt(y0 + h - rY)}`,
    `V${fmt(y0 + rY)}`,
    `A${fmt(rX)} ${fmt(rY)} 0 0 1 ${fmt(x0 + rX)} ${fmt(y0)}`,
    "Z",
  ].join("");
}

function ellipsePath(cx, cy, rx, ry) {
  const [x, y, a, b] = [cx, cy, rx, ry].map(Number);
  return `M${fmt(x - a)} ${fmt(y)}A${fmt(a)} ${fmt(b)} 0 1 0 ${fmt(x + a)} ${fmt(y)}A${fmt(a)} ${fmt(b)} 0 1 0 ${fmt(x - a)} ${fmt(y)}Z`;
}

function pointsPath(points, close) {
  const nums = points.trim().split(/[\s,]+/).map(Number);
  const pairs = [];
  for (let i = 0; i < nums.length; i += 2) pairs.push(`${fmt(nums[i])} ${fmt(nums[i + 1])}`);
  return `M${pairs[0]}${pairs.slice(1).map((p) => `L${p}`).join("")}${close ? "Z" : ""}`;
}

/** Converts one lucide SVG document into a list of SVG path strings. */
export function svgToPaths(svg) {
  const body = svg.replace(/<!--[\s\S]*?-->/g, "");
  const paths = [];
  for (const m of body.matchAll(/<(path|circle|ellipse|rect|line|polyline|polygon)\b([^>]*)\/?>/g)) {
    const [, tag, rest] = m;
    const a = attributes(rest);
    switch (tag) {
      case "path":
        paths.push(a.d);
        break;
      case "circle":
        paths.push(ellipsePath(a.cx ?? 0, a.cy ?? 0, a.r, a.r));
        break;
      case "ellipse":
        paths.push(ellipsePath(a.cx ?? 0, a.cy ?? 0, a.rx, a.ry));
        break;
      case "rect":
        paths.push(rectPath(a));
        break;
      case "line":
        paths.push(`M${fmt(a.x1 ?? 0)} ${fmt(a.y1 ?? 0)}L${fmt(a.x2 ?? 0)} ${fmt(a.y2 ?? 0)}`);
        break;
      case "polyline":
        paths.push(pointsPath(a.points, false));
        break;
      case "polygon":
        paths.push(pointsPath(a.points, true));
        break;
      default:
        throw new Error(`Unsupported SVG element <${tag}>`);
    }
  }
  if (!paths.length) throw new Error("SVG has no drawable elements");
  return paths;
}

export function readManifest() {
  return JSON.parse(readFileSync(iconPaths.manifest, "utf8"));
}

export function lucideVersions() {
  const lucide = JSON.parse(readFileSync(iconPaths.lucidePackage, "utf8")).version;
  const web = JSON.parse(readFileSync(iconPaths.webPackage, "utf8")).dependencies["lucide-react"].replace(/^[\^~]/, "");
  return { lucide, web };
}

const fnName = (name) => `${name[0].toLowerCase()}${name.slice(1)}Icon`;

export function emitIcons(manifest, readSvg, version) {
  const names = new Set();
  for (const icon of manifest.icons) {
    if (!/^[A-Z][A-Za-z0-9]*$/.test(icon.name)) throw new Error(`Icon name must be PascalCase: ${icon.name}`);
    if (names.has(icon.name)) throw new Error(`Duplicate icon: ${icon.name}`);
    names.add(icon.name);
  }
  const sorted = [...manifest.icons].sort((a, b) => a.name.localeCompare(b.name));
  const lines = [];
  lines.push(`// GENERATED by apps/android/scripts/generate_icons.mjs from lucide-static ${version} (ISC). Do not edit; run \`npm run generate\` in apps/android/scripts.`);
  lines.push('@file:Suppress("ktlint", "MaxLineLength")');
  lines.push("");
  lines.push("package dev.bento.designsystem.generated");
  lines.push("");
  lines.push("import androidx.compose.ui.graphics.Color");
  lines.push("import androidx.compose.ui.graphics.SolidColor");
  lines.push("import androidx.compose.ui.graphics.StrokeCap");
  lines.push("import androidx.compose.ui.graphics.StrokeJoin");
  lines.push("import androidx.compose.ui.graphics.vector.ImageVector");
  lines.push("import androidx.compose.ui.graphics.vector.addPathNodes");
  lines.push("import androidx.compose.ui.unit.dp");
  lines.push("");
  lines.push(`/** Lucide icons, stroke ${STROKE_DEFAULT}. Tint with \`BentoIcon\`; the paint color here is a placeholder. */`);
  lines.push("public object BentoIcons {");
  for (const icon of sorted) {
    lines.push(`    /** \`${icon.lucide}\` — ${icon.use} */`);
    lines.push(`    public val ${icon.name}: ImageVector by lazy { ${fnName(icon.name)}(${STROKE_DEFAULT}f, filled = false) }`);
    if (icon.filled) lines.push(`    public val ${icon.name}Filled: ImageVector by lazy { ${fnName(icon.name)}(${STROKE_DEFAULT}f, filled = true) }`);
  }
  lines.push("}");
  lines.push("");
  lines.push(`/** Navigation variants, stroke ${STROKE_NAV} (brand.md §8). */`);
  lines.push("public object BentoNavIcons {");
  for (const icon of sorted.filter((i) => i.nav)) {
    lines.push(`    public val ${icon.name}: ImageVector by lazy { ${fnName(icon.name)}(${STROKE_NAV}f, filled = false) }`);
  }
  lines.push("}");
  lines.push("");
  lines.push("/** Every generated icon by name, for previews and the kitchen sink. */");
  lines.push("public val BentoIconCatalog: List<Pair<String, ImageVector>> by lazy {");
  lines.push("    listOf(");
  for (const icon of sorted) lines.push(`        "${icon.name}" to BentoIcons.${icon.name},`);
  lines.push("    )");
  lines.push("}");
  lines.push("");
  for (const icon of sorted) {
    const paths = svgToPaths(readSvg(icon.lucide));
    lines.push(`private fun ${fnName(icon.name)}(stroke: Float, filled: Boolean): ImageVector = lucide(`);
    lines.push(`    "${icon.name}", stroke, filled,`);
    for (const p of paths) lines.push(`    "${p.replace(/\s+/g, " ").trim()}",`);
    lines.push(")");
    lines.push("");
  }
  lines.push("private fun lucide(name: String, stroke: Float, filled: Boolean, vararg paths: String): ImageVector {");
  lines.push("    val paint = SolidColor(Color.Black)");
  lines.push("    val builder = ImageVector.Builder(");
  lines.push('        name = if (filled) "$name.filled" else "$name.$stroke",');
  lines.push("        defaultWidth = 24.dp,");
  lines.push("        defaultHeight = 24.dp,");
  lines.push("        viewportWidth = 24f,");
  lines.push("        viewportHeight = 24f,");
  lines.push("    )");
  lines.push("    for (path in paths) {");
  lines.push("        builder.addPath(");
  lines.push("            pathData = addPathNodes(path),");
  lines.push("            fill = if (filled) paint else null,");
  lines.push("            stroke = paint,");
  lines.push("            strokeLineWidth = stroke,");
  lines.push("            strokeLineCap = StrokeCap.Round,");
  lines.push("            strokeLineJoin = StrokeJoin.Round,");
  lines.push("        )");
  lines.push("    }");
  lines.push("    return builder.build()");
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

export function generateIcons() {
  const { lucide, web } = lucideVersions();
  if (lucide !== web) throw new Error(`lucide-static ${lucide} must match lucide-react ${web} from apps/web/package.json`);
  const readSvg = (name) => {
    const file = join(iconPaths.lucideIcons, `${name}.svg`);
    if (!existsSync(file)) throw new Error(`Unknown lucide icon: ${name}`);
    return readFileSync(file, "utf8");
  };
  return { [iconPaths.kotlin]: emitIcons(readManifest(), readSvg, lucide) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (!existsSync(iconPaths.lucidePackage)) {
    console.error("lucide-static is not installed; run `npm ci` in apps/android/scripts.");
    process.exit(1);
  }
  const check = process.argv.includes("--check");
  const drift = writeOrCheck(generateIcons(), check);
  if (drift.length) {
    console.error(`Icons drifted from icons.json/lucide-static; run \`npm run generate\` in apps/android/scripts:\n  ${drift.join("\n  ")}`);
    process.exit(1);
  }
  if (!check) console.log("Bento icons generated.");
}

export const _internal = { rectPath, ellipsePath, pointsPath };
