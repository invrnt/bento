class _Defaults(dict[str, Any]):
    def __missing__(self, key: str) -> str:
        return "?"


class Translator:
    def __init__(self, lang: str = "es") -> None:
        self.lang = lang if lang in LANGS else "es"
        self._strings = EN if self.lang == "en" else ES

    def __call__(self, key: str, **params: Any) -> str:
        template = self._strings.get(key) or ES.get(key) or key
        try:
            return template.format_map(_Defaults(params))
        except (ValueError, IndexError):
            return template

    def has(self, key: str) -> bool:
        return key in self._strings

    def error_message(self, code: str, fallback: str, details: Mapping[str, Any]) -> str:
        template = ERRORS[self.lang].get(code)
        if template is None:
            return fallback or code
        try:
            return template.format_map(_Defaults({**details, "message": fallback}))
        except (ValueError, IndexError):
            return fallback or code

    def attention(self, item: Mapping[str, Any]) -> str:
        key = str(item.get("title_key") or f"activity.attention.{item.get('kind')}")
        raw = item.get("params")
        params: dict[str, Any] = dict(raw) if isinstance(raw, dict) else {}
        return self(key, **params) if self.has(key) else str(item.get("kind"))


def detect_lang(explicit: str | None, environ: Mapping[str, str], config_file: Path | None = None) -> str:
    """--lang, then BENTO_LANG, then the profile preference, then LANG/LC_*; Spanish by default."""
    if explicit in LANGS:
        return str(explicit)
    configured = environ.get("BENTO_LANG", "").strip().lower()[:2]
    if configured in LANGS:
        return configured
    if config_file is not None:
        from bento.interfaces.cli.profiles import read_json

        data = read_json(config_file)
        if isinstance(data, dict) and data.get("lang") in LANGS:
            return str(data["lang"])
    for name in ("LC_ALL", "LC_MESSAGES", "LANG"):
        value = environ.get(name, "").strip().lower()
        if value:
            return "en" if value.startswith("en") else "es"
    return "es"

