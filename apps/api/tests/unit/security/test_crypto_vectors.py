FIXTURE = Path(__file__).parent / "fixtures" / "crypto_vectors.json"
REGENERATE = os.environ.get("BENTO_REGENERATE_CRYPTO_VECTORS") == "1"
VAULT_ID = "vlt_kat"
PAIRING_PASSWORD = b"MXR9T4WA"
FALLBACK_REQUEST_ID = "req_kat_ñ"
WRAPPING_KEY = bytes(range(64, 96))


def _keyring() -> VaultKeyring:
    return VaultKeyring(vault_id=VAULT_ID, current_epoch=2, keys={1: bytes(range(32)), 2: bytes(range(32, 64))})


def _blob_params() -> BlobCipherParams:
    return BlobCipherParams(
        epoch=1, file_salt=bytes(range(100, 116)), nonce_prefix=bytes(range(200, 207)), segment_size=4096
    )


def _pattern(size: int) -> bytes:
    return bytes(index % 251 for index in range(size))


def _compute_vectors(tmp_path: Path) -> dict[str, Any]:
    keyring = _keyring()
    labels = [purpose.value for purpose in KeyPurpose] + ["pairing"]
    vectors: dict[str, Any] = {
        "inputs": {
            "vault_id": VAULT_ID,
            "vmk": {"1": keyring.keys[1].hex(), "2": keyring.keys[2].hex()},
            "pairing_password": PAIRING_PASSWORD.decode(),
            "wrapping_key": WRAPPING_KEY.hex(),
        },
        "subkeys": {
            f"{label}@{epoch}": vault_subkey(keyring, label, epoch).hex() for label in labels for epoch in (1, 2)
        },
    }

    crypto = VaultCrypto(random_bytes=DeterministicRandom(b"vault"))
    vectors["keyring_json"] = crypto.keyring_to_bytes(keyring).decode()

    params = _blob_params()
    cipher = StreamingBlobCipher()
    blobs: dict[str, Any] = {}
    for size in (0, 1, 4095, 4096, 4097, 9000):
        source = tmp_path / f"plain-{size}"
        source.write_bytes(_pattern(size))
        asyncio.run(cipher.encrypt_file(source, tmp_path / f"blob-{size}", keyring=keyring, params=params))
        ciphertext = (tmp_path / f"blob-{size}").read_bytes()
        entry: dict[str, Any] = {"size": len(ciphertext), "sha256": hashlib.sha256(ciphertext).hexdigest()}
        if size <= 1:
            entry["hex"] = ciphertext.hex()
        blobs[str(size)] = entry
    vectors["blob_v2"] = {
        "params": {
            "epoch": params.epoch,
            "file_salt": params.file_salt.hex(),
            "nonce_prefix": params.nonce_prefix.hex(),
            "segment_size": params.segment_size,
        },
        "header": encode_blob_header(params).hex(),
        "file_key": blob_file_key(keyring, 1, params.file_salt).hex(),
        "ciphertexts": blobs,
    }

    vectors["envelope"] = {
        purpose.name.lower(): crypto.seal(keyring, purpose, b"envelope payload", aad=b"aad").hex()
        for purpose in SealPurpose
    }
    vectors["envelope_json"] = crypto.seal_json(
        keyring, SealPurpose.SYNC, {"bento": "sync-batch", "v": 1, "ops": [{"filename": "café.jpg"}]}
    ).hex()

    header_unsigned = canonical_json({"bento": "vault-header", "v": 1, "vault_id": VAULT_ID, "current_epoch": 2})
    vectors["header_mac"] = {"unsigned": header_unsigned.decode(), "mac": crypto.header_mac(keyring, header_unsigned)}

    recovery_code = crypto.generate_recovery_code()
    secret_bits = int(
        "".join(f"{'0123456789ABCDEFGHJKMNPQRSTVWXYZ'.index(char):05b}" for char in recovery_code.replace("-", "")), 2
    )
    secret = (secret_bits >> 20).to_bytes(20, "big")
    assert secret_bits & 0xFFFFF == int.from_bytes(hashlib.sha256(secret).digest()[:3], "big") >> 4
    wrap = crypto.wrap_for_recovery(keyring, recovery_code)
    vectors["recovery"] = {
        "code": recovery_code,
        "secret": secret.hex(),
        "wrap_key": recovery_wrap_key(secret, VAULT_ID).hex(),
        "wrap": {"alg": wrap.alg, "nonce": wrap.nonce, "wrapped_keyring": wrap.wrapped_keyring},
    }

    identity = crypto.generate_device_identity()
    vectors["device_identity"] = {
        "device_id": identity.device_id,
        "public_key": identity.public_key.hex(),
        "serialized": crypto.device_identity_to_bytes(identity).decode(),
    }
    vectors["sealed_box"] = crypto.seal_for_device(identity.public_key, b"sealed keyring", aad=VAULT_ID.encode()).hex()

    pairing = PairingCryptoFactory(random_bytes=DeterministicRandom(b"pairing"))
    host = pairing.host_session(PAIRING_PASSWORD)
    guest = pairing.guest_session(PAIRING_PASSWORD)
    host_hello, guest_hello = host.start(), guest.start()
    host.finish(guest_hello)
    guest.finish(host_hello)
    host_confirmation, guest_confirmation = host.confirmation(), guest.confirmation()
    host.verify_peer_confirmation(guest_confirmation)
    guest.verify_peer_confirmation(host_confirmation)
    vectors["pairing"] = {
        "host_hello": host_hello.hex(),
        "guest_hello": guest_hello.hex(),
        "host_confirmation": host_confirmation.hex(),
        "guest_confirmation": guest_confirmation.hex(),
        "sas": list(host.sas()),
        "g2h_frames": [guest.encrypt_message({"type": "join_request", "n": index}).hex() for index in range(2)],
        "h2g_frames": [host.encrypt_message({"type": "vault_grant", "n": index}).hex() for index in range(2)],
    }

    fallback = PairingCryptoFactory(random_bytes=DeterministicRandom(b"fallback"))
    first, second = fallback.fallback_keys(), fallback.fallback_keys()
    transcript = {
        "request_id": FALLBACK_REQUEST_ID,
        "guest_device_public_key": identity.public_key,
        "guest_ephemeral_public_key": first.public_key(),
        "host_ephemeral_public_key": second.public_key(),
    }
    guest_sas = first.sas_with(second.public_key(), **transcript)
    assert guest_sas == second.sas_with(first.public_key(), **transcript)
    vectors["fallback"] = {
        "public_keys": [first.public_key().hex(), second.public_key().hex()],
        "request_id": FALLBACK_REQUEST_ID,
        "guest_device_public_key": identity.public_key.hex(),
        "commitment": first.commitment(device_public_key=identity.public_key, request_id=FALLBACK_REQUEST_ID),
        "sas": list(guest_sas),
    }
    grant_key = first.grant_key_with(second.public_key(), **transcript)
    assert grant_key == second.grant_key_with(first.public_key(), **transcript)
    vectors["fallback_grant"] = {
        "grant_key": grant_key.hex(),
        "grant": second.seal_grant(first.public_key(), b"sealed keyring", **transcript).hex(),
    }

    store = WrappedFileKeyStore(tmp_path / "secure", WRAPPING_KEY, random_bytes=DeterministicRandom(b"keystore"))
    asyncio.run(store.put("vault.keyring", b"key store secret"))
    vectors["key_store_file"] = (tmp_path / "secure" / "vault.keyring.bin").read_bytes().hex()
    vectors["sas_emojis"] = list(SAS_EMOJIS)
    return vectors


def _load_fixture() -> dict[str, Any]:
    if not FIXTURE.exists():
        pytest.fail(f"Missing {FIXTURE.name}; regenerate with BENTO_REGENERATE_CRYPTO_VECTORS=1")
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def test_formats_match_published_vectors(tmp_path: Path) -> None:
    vectors = _compute_vectors(tmp_path)
    if REGENERATE:
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE.write_text(json.dumps(vectors, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    fixture = _load_fixture()
    for section in sorted(set(fixture) | set(vectors)):
        assert vectors.get(section) == fixture.get(section), f"crypto format changed: {section}"


def test_published_vectors_still_decrypt(tmp_path: Path) -> None:
    fixture = _load_fixture()
    keyring = _keyring()
    crypto = VaultCrypto()

    for name, hex_value in fixture["envelope"].items():
        purpose = SealPurpose[name.upper()]
        assert crypto.open(keyring, purpose, bytes.fromhex(hex_value), aad=b"aad") == b"envelope payload"
    assert crypto.open_json(keyring, SealPurpose.SYNC, bytes.fromhex(fixture["envelope_json"]))["ops"] == [
        {"filename": "café.jpg"}
    ]

    mac = fixture["header_mac"]
    assert crypto.verify_header_mac(keyring, mac["unsigned"].encode(), mac["mac"])

    recovery = fixture["recovery"]
    wrap = RecoveryWrap(**recovery["wrap"])
    assert crypto.unwrap_with_recovery(wrap, recovery["code"], vault_id=VAULT_ID) == keyring

    identity = crypto.device_identity_from_bytes(fixture["device_identity"]["serialized"].encode())
    assert identity.public_key.hex() == fixture["device_identity"]["public_key"]
    assert (
        crypto.open_sealed(identity, bytes.fromhex(fixture["sealed_box"]), aad=VAULT_ID.encode()) == b"sealed keyring"
    )

    blob = fixture["blob_v2"]["ciphertexts"]["1"]["hex"]
    (tmp_path / "blob").write_bytes(bytes.fromhex(blob))
    asyncio.run(StreamingBlobCipher().decrypt_file(tmp_path / "blob", tmp_path / "plain", keyring=keyring))
    assert (tmp_path / "plain").read_bytes() == _pattern(1)

    (tmp_path / "secure").mkdir()
    (tmp_path / "secure" / "vault.keyring.bin").write_bytes(bytes.fromhex(fixture["key_store_file"]))
    store = WrappedFileKeyStore(tmp_path / "secure", WRAPPING_KEY)
    assert asyncio.run(store.get("vault.keyring")) == b"key store secret"

    assert crypto.keyring_from_bytes(fixture["keyring_json"].encode()) == keyring

    fallback = fixture["fallback"]
    assert verify_commitment(
        fallback["commitment"],
        eph_pub=bytes.fromhex(fallback["public_keys"][0]),
        device_public_key=bytes.fromhex(fallback["guest_device_public_key"]),
        request_id=fallback["request_id"],
    )
    assert len(b64url_decode(mac["mac"])) == 32


def _hkdf(ikm: bytes, salt: bytes | None, info: bytes, length: int = 32) -> bytes:
    return HKDF(algorithm=hashes.SHA256(), length=length, salt=salt, info=info).derive(ikm)


def _hmac(key: bytes, message: bytes) -> bytes:
    mac = hmac.HMAC(key, hashes.SHA256())
    mac.update(message)
    return mac.finalize()


def test_published_vectors_follow_spec_formulas() -> None:
    """Recompute every format straight from the architecture spec using raw primitives."""
    fixture = _load_fixture()
    vmk1, vmk2 = bytes(range(32)), bytes(range(32, 64))
    salt = VAULT_ID.encode()

    for name, value in fixture["subkeys"].items():
        label, epoch = name.split("@")
        assert _hkdf({"1": vmk1, "2": vmk2}[epoch], salt, b"bento/v1/" + label.encode()).hex() == value

    blob = fixture["blob_v2"]
    file_salt, prefix = bytes(range(100, 116)), bytes(range(200, 207))
    header = b"BNT2" + bytes([2]) + (1).to_bytes(4, "big") + file_salt + (4096).to_bytes(4, "big") + prefix
    assert len(header) == 36 and header.hex() == blob["header"]
    file_key = _hkdf(_hkdf(vmk1, salt, b"bento/v1/blob"), file_salt, b"bento/v1/blob-file")
    assert file_key.hex() == blob["file_key"]
    aead = AESGCM(file_key)

    def segment(index: int, last: bool, data: bytes) -> bytes:
        return aead.encrypt(prefix + index.to_bytes(4, "big") + bytes([1 if last else 0]), data, header)

    expected = {
        0: header + segment(0, True, b""),
        1: header + segment(0, True, _pattern(1)),
        4095: header + segment(0, True, _pattern(4095)),
        4096: header + segment(0, True, _pattern(4096)),
        4097: header + segment(0, False, _pattern(4097)[:4096]) + segment(1, True, _pattern(4097)[4096:]),
        9000: header
        + segment(0, False, _pattern(9000)[:4096])
        + segment(1, False, _pattern(9000)[4096:8192])
        + segment(2, True, _pattern(9000)[8192:]),
    }
    for size, ciphertext in expected.items():
        entry = blob["ciphertexts"][str(size)]
        assert len(ciphertext) == entry["size"] and hashlib.sha256(ciphertext).hexdigest() == entry["sha256"]

    codes = {"sync": 1, "snapshot": 2, "device_record": 3, "pairing": 4}
    infos = {"sync": b"sync", "snapshot": b"snapshot", "device_record": b"device-record", "pairing": b"pairing"}
    for name, value in fixture["envelope"].items():
        envelope = bytes.fromhex(value)
        assert envelope[:4] == b"BENV" and envelope[4] == 1 and envelope[5] == codes[name]
        assert envelope[6:10] == (2).to_bytes(4, "big")
        key = _hkdf(vmk2, salt, b"bento/v1/" + infos[name])
        plaintext = AESGCM(key).decrypt(envelope[10:22], envelope[22:], envelope[:22] + b"aad")
        assert plaintext == b"envelope payload"

    mac = fixture["header_mac"]
    raw_mac = _hmac(_hkdf(vmk2, salt, b"bento/v1/header-mac"), mac["unsigned"].encode())
    assert b64url_decode(mac["mac"]) == raw_mac and "=" not in mac["mac"]

    recovery = fixture["recovery"]
    secret = bytes.fromhex(recovery["secret"])
    wrap_key = _hkdf(secret, b"bento/v1/recovery", salt)
    assert wrap_key.hex() == recovery["wrap_key"]
    keyring_json = AESGCM(wrap_key).decrypt(
        b64url_decode(recovery["wrap"]["nonce"]), b64url_decode(recovery["wrap"]["wrapped_keyring"]), salt
    )
    assert keyring_json.decode() == fixture["keyring_json"]

    identity = json.loads(fixture["device_identity"]["serialized"])
    private = X25519PrivateKey.from_private_bytes(b64url_decode(identity["private_key"]))
    recipient_public = private.public_key().public_bytes_raw()
    sealed = bytes.fromhex(fixture["sealed_box"])
    assert sealed[:4] == b"BBOX" and sealed[4] == 1
    ephemeral_public, nonce = sealed[5:37], sealed[37:49]
    shared = private.exchange(X25519PublicKey.from_public_bytes(ephemeral_public))
    box_key = _hkdf(shared, ephemeral_public + recipient_public, b"bento/v1/sealed-box")
    assert AESGCM(box_key).decrypt(nonce, sealed[49:], sealed[:49] + salt) == b"sealed keyring"

    pairing = fixture["pairing"]
    entropy = DeterministicRandom(b"pairing")
    host = SPAKE2_A(PAIRING_PASSWORD, idA=b"bento-host", idB=b"bento-guest", entropy_f=entropy)
    guest = SPAKE2_B(PAIRING_PASSWORD, idA=b"bento-host", idB=b"bento-guest", entropy_f=entropy)
    host_hello, guest_hello = host.start(), guest.start()
    assert (b"\x01" + host_hello).hex() == pairing["host_hello"]
    assert (b"\x01" + guest_hello).hex() == pairing["guest_hello"]
    shared_key = host.finish(guest_hello)
    assert shared_key == guest.finish(host_hello)
    assert (b"\x02" + _hmac(shared_key, b"host-confirm")).hex() == pairing["host_confirmation"]
    assert (b"\x02" + _hmac(shared_key, b"guest-confirm")).hex() == pairing["guest_confirmation"]
    sas_value = int.from_bytes(_hkdf(shared_key, None, b"bento/v1/pairing/sas", 3), "big")
    assert pairing["sas"] == [SAS_EMOJIS[(sas_value >> shift) & 63] for shift in (18, 12, 6, 0)]
    for direction, label, kind in (("g2h_frames", b"g2h", "join_request"), ("h2g_frames", b"h2g", "vault_grant")):
        direction_key = AESGCM(_hkdf(shared_key, None, b"bento/v1/pairing/" + label))
        for counter, frame_hex in enumerate(pairing[direction]):
            frame = bytes.fromhex(frame_hex)
            assert frame[0] == 0x03
            nonce = bytes(4) + counter.to_bytes(8, "big")
            assert json.loads(direction_key.decrypt(nonce, frame[1:], None)) == {"type": kind, "n": counter}

    fallback = fixture["fallback"]
    fallback_entropy = DeterministicRandom(b"fallback")
    first = X25519PrivateKey.from_private_bytes(fallback_entropy(32))
    second = X25519PrivateKey.from_private_bytes(fallback_entropy(32))
    publics = [first.public_key().public_bytes_raw(), second.public_key().public_bytes_raw()]
    assert [value.hex() for value in publics] == fallback["public_keys"]
    request_id = fallback["request_id"].encode("utf-8")
    device_key = bytes.fromhex(fallback["guest_device_public_key"])
    assert device_key == recipient_public
    commitment = hashlib.sha256(b"bento/v1/pair-commit" + publics[0] + device_key + request_id).digest()
    assert b64url_decode(fallback["commitment"]) == commitment and "=" not in fallback["commitment"]
    fallback_shared = first.exchange(second.public_key())
    transcript_salt = hashlib.sha256(request_id + device_key + publics[0] + publics[1]).digest()
    sas_bits = _hkdf(fallback_shared, transcript_salt, b"bento/v1/pairing/fallback-sas", 3)
    fallback_value = int.from_bytes(sas_bits, "big")
    assert fallback["sas"] == [SAS_EMOJIS[(fallback_value >> shift) & 63] for shift in (18, 12, 6, 0)]
    grant_key = _hkdf(fallback_shared, transcript_salt, b"bento/v1/pairing/fallback-grant")
    assert grant_key.hex() == fixture["fallback_grant"]["grant_key"]
    grant = bytes.fromhex(fixture["fallback_grant"]["grant"])
    assert AESGCM(grant_key).decrypt(grant[:12], grant[12:], request_id) == b"sealed keyring"

    stored = bytes.fromhex(fixture["key_store_file"])
    assert stored[:4] == b"BKEY" and stored[4] == 1
    assert AESGCM(WRAPPING_KEY).decrypt(stored[5:17], stored[17:], b"vault.keyring") == b"key store secret"
